import { call, pool, pct, tally, sql, log, ok, load, save, rssMB } from './lib.mjs';
const N = Number(process.argv[2] || 2000);
log(`== P3: login ${N} user berbeda ==`);
sql('update User set sessionId=NULL, lastSeenAt=NULL where email like "%@loadtest.test"');
const users = load('users').slice(0, N);
const t0 = Date.now();
const jars = users.map(() => ({}));
const rs = await pool(users, 20, (u, i) => call('POST', '/auth/login', { body: { email: u.email, password: u.password }, jar: jars[i] }));
log('status login:', JSON.stringify(tally(rs)), `durasi ${((Date.now() - t0) / 1000).toFixed(0)}s`, `p50=${pct(rs.map((r) => r.ms), .5)}ms p95=${pct(rs.map((r) => r.ms), .95)}ms`);
ok(`${N} login berhasil`, rs.every((r) => r.status === 200), JSON.stringify(tally(rs)));
save('jars', jars);
const wrong = await call('POST', '/auth/login', { body: { email: users[0].email, password: 'SalahTotal1' } });
ok('sandi salah -> 401', wrong.status === 401, wrong.data?.message);
const unknown = await call('POST', '/auth/login', { body: { email: 'tidakada@loadtest.test', password: 'SalahTotal1' } });
ok('email tak dikenal -> pesan sama persis (anti enumerasi)', unknown.status === 401 && unknown.data?.message === wrong.data?.message);
const me = await call('GET', '/auth/me', { jar: jars[5] });
ok('cookie sesi valid -> /auth/me 200', me.status === 200 && me.data?.user?.email === users[5].email);
const noCookie = await call('GET', '/auth/me');
ok('tanpa cookie -> 401', noCookie.status === 401);
const csrf = await fetch('http://127.0.0.1:3000/api/transactions/1/cancel', { method: 'POST', headers: { Cookie: jars[5].cookie, 'X-Forwarded-For': '10.200.0.1' } });
ok('anti-CSRF: POST tanpa header X-Requested-With ditolak (403)', csrf.status === 403, `status ${csrf.status}`);
